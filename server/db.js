/** Tables in an order that respects foreign keys. */
export const TABLES = ['users', 'sessions', 'listings', 'photos', 'reviews', 'favorites', 'conversations', 'messages', 'deal_requests', 'dgis_cache', 'reports', 'duplicate_dismissals', 'admin_log'];

export const isUniqueViolation = (error) => error?.code === '23505';

// Refused connections, a server that is still starting, and a database not created yet.
const NOT_READY = new Set(['ECONNREFUSED', 'ECONNRESET', '57P03', '3D000']);

/** Query helpers shared by the pool and by a transaction's client. */
function wrap(runner, pool) {
  const db = {
    all: async (sql, params = []) => (await runner.query(sql, params)).rows,
    get: async (sql, params = []) => (await runner.query(sql, params)).rows[0],
    run: async (sql, params = []) => (await runner.query(sql, params)).rowCount,
    /** Runs `fn` inside one transaction. A nested call joins the outer one. */
    async transaction(fn) {
      if (runner !== pool) return fn(db);
      const client = await pool.connect();
      try {
        await client.query('BEGIN');
        const result = await fn(wrap(client, pool));
        await client.query('COMMIT');
        return result;
      } catch (error) {
        await client.query('ROLLBACK').catch(() => {});
        throw error;
      } finally {
        client.release();
      }
    },
    close: () => pool.end(),
  };
  return db;
}

/**
 * Connects to PostgreSQL, waits up to `waitMs` for it to accept connections,
 * and creates any missing tables.
 */
export async function connectDb(connectionString, { waitMs = 0, onWait = () => {} } = {}) {
  const pool = new pg.Pool({ connectionString, max: 10 });
  // An idle connection that drops must not crash the server.
  pool.on('error', (error) => console.warn(`PostgreSQL connection lost: ${error.message}`));
  const deadline = Date.now() + waitMs;
  for (let attempt = 0; ; attempt += 1) {
    try {
      await pool.query('SELECT 1');
      break;
    } catch (error) {
      if (!NOT_READY.has(error.code) || Date.now() >= deadline) {
        await pool.end();
        throw error;
      }
      if (attempt === 0) onWait();
      await new Promise((resolve) => { setTimeout(resolve, 1000); });
    }
  }
  await pool.query(SCHEMA);
  return wrap(pool, pool);
}
